    //Esto es lo que se mostrará en la pantalla
    bool oled_task_user(void) {

        led_t led_state = host_keyboard_led_state(); // Nos da el estado del block num y CAPS lock
        
        switch (get_highest_layer(layer_state)) { // Estructura de casos
            case _ANIMACION: // Si estamos en la capa de animación
                render_animation();
                break;
            case _LOGO: // Si estamos en la capa del logo
                render_logo();
                break;
            case _ALTER: // Si estamos en la capa alternativa
                oled_set_cursor(0,0);
                oled_write_P(PSTR("DALE LIKE A ESTE"), false);
                oled_set_cursor(0,1);
                oled_write_P(PSTR("VIDEO Y COMPARTELO"), false);
                oled_set_cursor(0,2);
                oled_write_P(PSTR("CON TUS AMIGOS"), false);
                break;
            default: // Si estamos en la capa base (La por defecto)

                // Código válido si tenemos la pantalla en horizontal
                oled_set_cursor(0,0); // horizontal, vertical
                oled_write_P(PSTR("Layer: Base"), false);
                oled_set_cursor(0,1);
                oled_write_P(led_state.num_lock ? PSTR("NUM - ") : PSTR("     "), false);
                oled_write_P(led_state.caps_lock ? PSTR("CAPS") : PSTR("    "), false);
                oled_set_cursor(0,2);
                oled_write_P(PSTR("WPM: "), false);
                oled_write(get_u8_str(get_current_wpm(), '0'), false);

                // Código válido si tenemos la pantalla girada 90º
                oled_write_P(PSTR("Lyr:\n"), false);
                oled_write_P(PSTR("Base\n"), false);
                oled_write_P(led_state.num_lock ? PSTR("\nNUM\n") : PSTR("\n"), false);
                oled_write_P(led_state.caps_lock ? PSTR("CAP\n") : PSTR("\n"), false);
                oled_write_P(led_state.scroll_lock ? PSTR("SCR\n") : PSTR("\n"), false);
                oled_write_P(PSTR("WPM: "), false);
                oled_write(get_u8_str(get_current_wpm(), '0'), false);
        }

        return false;
    }


