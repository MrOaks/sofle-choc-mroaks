/**************************************************** KEYCODE PROCESSING */
bool process_record_user(uint16_t keycode, keyrecord_t *record) {

  if (record->event.pressed) {
    add_keylog(keycode);
  }

  switch (keycode) {
    case UML_A:
      if (record->event.pressed) {
          tap_code(KC_CAPS);
          tap_code(KC_A);
          register_code(KC_RIGHT_SHIFT);
          tap_code(KC_QUOTE);
          unregister_code(KC_RIGHT_SHIFT);
      } else {
      }
      break;
    case UML_U:
      if (record->event.pressed) {
          tap_code(KC_CAPS);
          tap_code(KC_U);
          register_code(KC_RIGHT_SHIFT);
          tap_code(KC_QUOTE);
          unregister_code(KC_RIGHT_SHIFT);
      } else {
      }
      break;
    case UML_O:
      if (record->event.pressed) {
        tap_code(KC_CAPS);
        tap_code(KC_O);
        register_code(KC_RIGHT_SHIFT);
        tap_code(KC_QUOTE);
        unregister_code(KC_RIGHT_SHIFT);
      } else {
      }
      break;
    case ESIGN:
      if (record->event.pressed) {
          tap_code(KC_CAPS);
          tap_code(KC_C);
          tap_code(KC_EQUAL);
      } else {
      }
      break;
    case BRK_L1:  // Left Bracket 1: [
      if (record->event.pressed) {
          tap_code(KC_LEFT_BRACKET);
      } else {
      }
      break;
    case BRK_R1:  // Right Bracket 1: [
      if (record->event.pressed) {
          tap_code(KC_RIGHT_BRACKET);
      } else {
      }
      break;
    case BRK_L2:  // Left Bracket 2: {
      if (record->event.pressed) {
          register_code(KC_RIGHT_SHIFT);
          tap_code(KC_LEFT_BRACKET);
          unregister_code(KC_RIGHT_SHIFT);
      } else {
      }
      break;
    case BRK_R2:  // Right Bracket 2: }
      if (record->event.pressed) {
          register_code(KC_RIGHT_SHIFT);
          tap_code(KC_RIGHT_BRACKET);
          unregister_code(KC_RIGHT_SHIFT);
      } else {
      }
      break;

/* KEYBOARD PET STATUS START */

    case KC_LCTL:
    case KC_RCTL:
      if (record->event.pressed) {
        isSneaking = true;
      } else {
        isSneaking = false;
      }
      break;
    case KC_SPC:
      if (record->event.pressed) {
        isJumping  = true;
        showedJump = false;
      } else {
        isJumping = false;
      }
      break;

/* KEYBOARD PET STATUS END */

  } // end switch
  return true;
};

